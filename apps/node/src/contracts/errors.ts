export type ErrorCode = (typeof ERROR_CODES)[keyof typeof ERROR_CODES];

export interface ClawperatorError {
  code: ErrorCode;
  message: string;
  hint?: string;
  details?: Record<string, unknown>;
  fallback_instructions_path?: string;
}

export interface TimeoutDiagnostics {
  code: typeof ERROR_CODES.RESULT_ENVELOPE_TIMEOUT;
  message: string;
  details?: Record<string, unknown>;
  lastCorrelatedEvents?: string[];
  broadcastDispatchStatus?: string;
  deviceId?: string;
  operatorPackage?: string;
}

export interface BroadcastDiagnostics {
  code: typeof ERROR_CODES.BROADCAST_FAILED | typeof ERROR_CODES.OPERATOR_NOT_INSTALLED;
  message: string;
  details?: Record<string, unknown>;
  lastCorrelatedEvents?: string[];
  broadcastDispatchStatus?: string;
  deviceId?: string;
  operatorPackage?: string;
}

export function isClawperatorError(e: unknown): e is ClawperatorError {
  return (
    typeof e === "object" &&
    e !== null &&
    "code" in e &&
    typeof (e as ClawperatorError).code === "string" &&
    "message" in e &&
    typeof (e as ClawperatorError).message === "string"
  );
}

/** Additive host evidence; dispatch acknowledgement does not prove action completion. */
export type FailurePhase = "readiness" | "dispatch" | "result_wait" | "post_processing";
export type DispatchState = "not_dispatched" | "dispatched" | "unknown";
export interface ExecutionFailureEvidence extends Record<string, unknown> {
  phase: FailurePhase;
  dispatchState: DispatchState;
  commandId?: string;
  taskId?: string;
  earlierEffects?: Array<{ actionId: string; effect: "force_stop" }>;
  probeCommandId?: string;
  probeTaskId?: string;
  probeDispatchState?: DispatchState;
  probeStartedAt?: string;
  probeCompletedAt?: string;
  dispatchStartedAt?: string;
  startedAt: string;
  completedAt?: string;
  logPath?: string;
}
